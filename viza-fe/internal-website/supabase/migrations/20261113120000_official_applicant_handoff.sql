-- Open: called by the exact worker that owns a live processing lease. Creates
-- one queued handoff, writes the applicant-visible result, and releases the
-- queue lease in the same transaction.
CREATE OR REPLACE FUNCTION public.open_official_applicant_handoff(
  p_queue_id UUID,
  p_worker_id TEXT,
  p_application_id UUID,
  p_applicant_id UUID,
  p_browserbase_session_id TEXT,
  p_live_view_url TEXT,
  p_expires_at TIMESTAMPTZ,
  p_stopped_result JSONB
)
RETURNS TABLE (
  opened BOOLEAN,
  takeover_id UUID,
  application_id UUID,
  expires_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_application public.applications%ROWTYPE;
  v_queue public.submission_queue%ROWTYPE;
  v_session public.takeover_session%ROWTYPE;
  v_prefix TEXT;
  v_now TIMESTAMPTZ;
  v_worker_id TEXT := BTRIM(COALESCE(p_worker_id, ''));
  v_session_id TEXT := BTRIM(COALESCE(p_browserbase_session_id, ''));
  v_live_view_url TEXT := BTRIM(COALESCE(p_live_view_url, ''));
  v_takeover_id UUID;
  v_result JSONB;
  v_updated_rows INTEGER;
BEGIN
  IF p_queue_id IS NULL OR p_application_id IS NULL OR p_applicant_id IS NULL THEN
    RAISE EXCEPTION 'queue, application, and applicant ids are required'
      USING ERRCODE = '22023';
  END IF;
  IF v_worker_id = '' OR length(v_worker_id) > 200 THEN
    RAISE EXCEPTION 'worker id is required and must be at most 200 characters'
      USING ERRCODE = '22023';
  END IF;
  IF v_session_id = '' OR length(v_session_id) > 200 THEN
    RAISE EXCEPTION 'Browserbase session id is required and must be at most 200 characters'
      USING ERRCODE = '22023';
  END IF;
  IF v_live_view_url = '' OR length(v_live_view_url) > 4096 OR v_live_view_url !~* '^https://' THEN
    RAISE EXCEPTION 'live-view URL must be a bounded https:// URL'
      USING ERRCODE = '22023';
  END IF;
  IF p_expires_at IS NULL THEN
    RAISE EXCEPTION 'handoff expiry is required' USING ERRCODE = '22023';
  END IF;
  IF p_stopped_result IS NULL
    OR pg_catalog.jsonb_typeof(p_stopped_result) <> 'object'
    OR pg_catalog.pg_column_size(p_stopped_result) > 524288
    OR p_stopped_result ->> 'status' IS DISTINCT FROM 'awaiting_applicant_official_submit'
  THEN
    RAISE EXCEPTION 'handoff requires a bounded awaiting_applicant_official_submit result'
      USING ERRCODE = '22023';
  END IF;

  -- Lock order: application, then queue row, then handoff rows.
  SELECT application.*
  INTO v_application
  FROM public.applications AS application
  WHERE application.id = p_application_id
    AND application.applicant_id = p_applicant_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN;
  END IF;

  SELECT queue.*
  INTO v_queue
  FROM public.submission_queue AS queue
  WHERE queue.id = p_queue_id
    AND queue.application_id = p_application_id
    AND queue.locked_by = v_worker_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN;
  END IF;

  v_prefix := public.official_handoff_queue_prefix(v_queue.provider);
  IF v_prefix IS NULL
    OR v_queue.status IS DISTINCT FROM v_prefix || 'live_assisted_processing'
    OR v_queue.cancel_requested_at IS NOT NULL
  THEN
    RETURN;
  END IF;

  v_now := pg_catalog.clock_timestamp();
  IF v_queue.locked_until IS NULL OR v_queue.locked_until <= v_now THEN
    RETURN;
  END IF;
  IF p_expires_at <= v_now OR p_expires_at > v_now + INTERVAL '2 hours' THEN
    RAISE EXCEPTION 'handoff expiry must be in the next two hours'
      USING ERRCODE = '22023';
  END IF;

  -- A still-active handoff for this application is never superseded by a
  -- second open; an expired one is abandoned first.
  FOR v_session IN
    SELECT session.*
    FROM public.takeover_session AS session
    WHERE session.application_id = p_application_id
      AND session.handoff_kind = 'official_applicant_final_submit'
      AND session.status IN ('queued', 'claimed')
    ORDER BY session.id
    FOR UPDATE
  LOOP
    v_now := pg_catalog.clock_timestamp();
    IF v_session.expires_at IS NOT NULL AND v_session.expires_at > v_now THEN
      RETURN;
    END IF;
    UPDATE public.takeover_session AS session
    SET status = 'abandoned',
        operator_notes = 'superseded_after_official_handoff_expiry',
        closed_at = v_now
    WHERE session.id = v_session.id
      AND session.status IN ('queued', 'claimed');
    INSERT INTO public.takeover_action_log (takeover_id, action, detail, ts)
    VALUES (
      v_session.id, 'abandon',
      jsonb_build_object('kind', 'official_applicant_final_submit', 'reason', 'expired_before_reopen'),
      v_now
    );
  END LOOP;

  v_now := pg_catalog.clock_timestamp();
  IF v_queue.locked_until <= v_now THEN
    RETURN;
  END IF;

  v_takeover_id := pg_catalog.gen_random_uuid();
  v_result := p_stopped_result || jsonb_build_object(
    'handoffId', v_takeover_id,
    'handoffExpiresAt', p_expires_at
  );

  INSERT INTO public.takeover_session (
    id, job_id, submission_queue_id, application_id, applicant_id, status, reason,
    remote_debug_url, vnc_url, handoff_kind, expires_at, created_at
  )
  VALUES (
    v_takeover_id,
    NULL,
    p_queue_id,
    p_application_id,
    p_applicant_id,
    'queued',
    'Official form is filled and waiting for the applicant''s own final official submission',
    'browserbase-session:' || v_session_id,
    v_live_view_url,
    'official_applicant_final_submit',
    p_expires_at,
    v_now
  );

  INSERT INTO public.takeover_action_log (takeover_id, action, detail, ts)
  VALUES (
    v_takeover_id, 'open',
    jsonb_build_object(
      'kind', 'official_applicant_final_submit',
      'submission_queue_id', p_queue_id,
      'provider', v_queue.provider,
      'worker_id', v_worker_id,
      'expires_at', p_expires_at
    ),
    v_now
  );

  UPDATE public.applications AS application
  SET submission_result = v_result,
      submission_result_status = 'needs_user_action',
      submission_result_updated_at = v_now,
      updated_at = v_now
  WHERE application.id = p_application_id;
  GET DIAGNOSTICS v_updated_rows = ROW_COUNT;
  IF v_updated_rows <> 1 THEN
    RAISE EXCEPTION 'Application % disappeared during official handoff open', p_application_id
      USING ERRCODE = '55000';
  END IF;

  UPDATE public.submission_queue AS queue
  SET status = v_prefix || 'applicant_handoff',
      current_stage = 'awaiting_applicant_official_submit',
      locked_by = NULL,
      locked_until = NULL,
      locked_at = NULL,
      updated_at = v_now
  WHERE queue.id = p_queue_id
    AND queue.locked_by = v_worker_id;
  GET DIAGNOSTICS v_updated_rows = ROW_COUNT;
  IF v_updated_rows <> 1 THEN
    RAISE EXCEPTION 'Queue row % changed during official handoff open', p_queue_id
      USING ERRCODE = '55000';
  END IF;

  RETURN QUERY SELECT TRUE, v_takeover_id, p_application_id, p_expires_at;
END;
$$;

