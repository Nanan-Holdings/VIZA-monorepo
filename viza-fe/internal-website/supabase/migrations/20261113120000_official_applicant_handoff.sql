-- Official applicant final-submit handoff for legacy submission_queue runners.
--
-- Product policy (2026-11): VIZA never clicks an official final submit or
-- pays a government fee. The runner fills the official portal, keeps that
-- exact Browserbase session alive, and hands it to the owning applicant, who
-- reviews, declares, submits, and pays on the official site themselves. The
-- runner later re-attaches to the same session and records the official
-- receipt.
--
-- Unlike the Taiwan runner_job handoff (0149, unchanged here), the sticky
-- Indonesia worker cannot hold its queue lease while an applicant reviews the
-- page, so the queue row leaves the processing state when the handoff opens
-- and is re-leased briefly by a watcher for each receipt check.
--
-- Lifecycle of the queue row: <prefix>live_assisted_processing --open-->
-- <prefix>applicant_handoff --settle submitted--> <prefix>applicant_submitted
-- (the session stays claimable so the applicant can finish paying) --settle
-- closed--> session completed. An unsubmitted handoff that expires becomes
-- <prefix>applicant_handoff_expired and may be regenerated by the applicant.
--
-- Supported providers are allowlisted in
-- public.official_handoff_queue_prefix(). Add a provider there only after its
-- runner stops before the official final submit.

ALTER TABLE public.takeover_session
  ADD COLUMN IF NOT EXISTS submission_queue_id UUID
    REFERENCES public.submission_queue(id) ON DELETE CASCADE;

ALTER TABLE public.takeover_session
  ALTER COLUMN job_id DROP NOT NULL;

-- Cooperative applicant cancellation for a run already in progress. The
-- runner checks it between official-portal stages and stops itself.
ALTER TABLE public.submission_queue
  ADD COLUMN IF NOT EXISTS cancel_requested_at TIMESTAMPTZ;

COMMENT ON COLUMN public.submission_queue.cancel_requested_at IS
  'Set by cancel_official_applicant_submission while a runner holds the row; the runner stops at its next stage and clears it.';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_constraint
    WHERE conname = 'takeover_session_owner_check'
      AND conrelid = 'public.takeover_session'::regclass
  ) THEN
    ALTER TABLE public.takeover_session
      ADD CONSTRAINT takeover_session_owner_check
      CHECK (num_nonnulls(job_id, submission_queue_id) = 1);
  END IF;
END;
$$;

COMMENT ON COLUMN public.takeover_session.submission_queue_id IS
  'Legacy submission_queue owner for official_applicant_final_submit handoffs. Exactly one of job_id or submission_queue_id identifies the runner work.';

CREATE UNIQUE INDEX IF NOT EXISTS takeover_session_official_active_unique_idx
  ON public.takeover_session (application_id)
  WHERE handoff_kind = 'official_applicant_final_submit'
    AND status IN ('queued', 'claimed');

CREATE INDEX IF NOT EXISTS takeover_session_official_queue_status_idx
  ON public.takeover_session (submission_queue_id, status, expires_at)
  WHERE handoff_kind = 'official_applicant_final_submit';

CREATE INDEX IF NOT EXISTS submission_queue_official_handoff_watch_idx
  ON public.submission_queue (status, locked_until, locked_at)
  WHERE status IN (
    'id_c1_applicant_handoff', 'id_b1_evoa_applicant_handoff',
    'id_c1_applicant_submitted', 'id_b1_evoa_applicant_submitted'
  );

-- Provider allowlist. Returns the queue status prefix for a supported provider
-- and NULL for every other provider.
CREATE OR REPLACE FUNCTION public.official_handoff_queue_prefix(p_provider TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT CASE p_provider
    WHEN 'indonesia_c1_live' THEN 'id_c1_'
    WHEN 'indonesia_b1_evoa_live' THEN 'id_b1_evoa_'
    ELSE NULL
  END;
$$;

