-- Claim: called by the authenticated application API for the exact owning
-- applicant. Returns the live-view URL only for an unexpired handoff whose
-- queue row is waiting for the applicant, or already submitted but still open
-- so the applicant can return to pay. Same-applicant retries are idempotent;
-- any other applicant receives no row.
CREATE OR REPLACE FUNCTION public.claim_official_applicant_handoff(
  p_takeover_id UUID,
  p_application_id UUID,
  p_applicant_id UUID
)
RETURNS TABLE (
  claimed BOOLEAN,
  takeover_id UUID,
  application_id UUID,
  live_view_url TEXT,
  expires_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_session public.takeover_session%ROWTYPE;
  v_queue public.submission_queue%ROWTYPE;
  v_prefix TEXT;
  v_now TIMESTAMPTZ;
  v_updated_rows INTEGER;
BEGIN
  IF p_takeover_id IS NULL OR p_application_id IS NULL OR p_applicant_id IS NULL THEN
    RAISE EXCEPTION 'takeover, application, and applicant ids are required'
      USING ERRCODE = '22023';
  END IF;

  PERFORM 1
  FROM public.applications AS application
  WHERE application.id = p_application_id
    AND application.applicant_id = p_applicant_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN;
  END IF;

  SELECT session.*
  INTO v_session
  FROM public.takeover_session AS session
  WHERE session.id = p_takeover_id
    AND session.application_id = p_application_id
    AND session.applicant_id = p_applicant_id
    AND session.handoff_kind = 'official_applicant_final_submit'
    AND session.submission_queue_id IS NOT NULL
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN;
  END IF;

  SELECT queue.*
  INTO v_queue
  FROM public.submission_queue AS queue
  WHERE queue.id = v_session.submission_queue_id
    AND queue.application_id = p_application_id;
  IF NOT FOUND THEN
    RETURN;
  END IF;
  v_prefix := public.official_handoff_queue_prefix(v_queue.provider);
  IF v_prefix IS NULL OR v_queue.status NOT IN (
    v_prefix || 'applicant_handoff',
    v_prefix || 'applicant_submitted'
  ) THEN
    RETURN;
  END IF;

  v_now := pg_catalog.clock_timestamp();
  IF v_session.expires_at IS NULL OR v_session.expires_at <= v_now THEN
    RETURN;
  END IF;

  IF v_session.status = 'claimed' THEN
    IF v_session.claimed_by IS DISTINCT FROM p_applicant_id THEN
      RETURN;
    END IF;
    RETURN QUERY SELECT TRUE, v_session.id, p_application_id,
      v_session.vnc_url, v_session.expires_at;
    RETURN;
  END IF;
  IF v_session.status <> 'queued' OR v_session.vnc_url IS NULL THEN
    RETURN;
  END IF;

  UPDATE public.takeover_session AS session
  SET status = 'claimed',
      claimed_by = p_applicant_id,
      claimed_at = v_now
  WHERE session.id = p_takeover_id
    AND session.status = 'queued'
    AND session.expires_at > v_now;
  GET DIAGNOSTICS v_updated_rows = ROW_COUNT;
  IF v_updated_rows <> 1 THEN
    RETURN;
  END IF;

  INSERT INTO public.takeover_action_log (takeover_id, action, actor_user_id, detail, ts)
  VALUES (
    p_takeover_id, 'claim', p_applicant_id,
    jsonb_build_object('kind', 'official_applicant_final_submit'), v_now
  );

  RETURN QUERY SELECT TRUE, p_takeover_id, p_application_id,
    v_session.vnc_url, v_session.expires_at;
END;
$$;

